#define STATE_FIELD(id_, type_, field_, wire_type_, record_id_, count_, flags_) \
	{ \
		.name = #field_, \
		.id = (id_), \
		.wire_type = (wire_type_), \
		.record_id = (record_id_), \
		.offset = offsetof(type_, field_), \
		.size = sizeof(((type_ *)0)->field_), \
		.count = (count_), \
		.flags = (flags_), \
	}

#define SERIAL_FIELD(id_, type_, field_, wire_type_, record_id_) \
	STATE_FIELD(id_, type_, field_, wire_type_, record_id_, 1, NES_STATE_FIELD_SERIALIZED)

#define SERIAL_ARRAY_FIELD(id_, type_, field_, wire_type_, record_id_) \
	STATE_FIELD(id_, type_, field_, wire_type_, record_id_, ArrayCount(((type_ *)0)->field_), \
		NES_STATE_FIELD_SERIALIZED)

#define DEBUG_SERIAL_FIELD(id_, type_, field_, wire_type_, record_id_) \
	STATE_FIELD(id_, type_, field_, wire_type_, record_id_, 1, \
		NES_STATE_FIELD_SERIALIZED | NES_STATE_FIELD_DEBUG_VISIBLE)

