static const SerializeRecordMap nes_records =
{
	.records = nes_state_records,
	.record_count = ArrayCount(nes_state_records),
};

const SerializeRecordMap *nes_state_record_map(void)
{
	return &nes_records;
}

const NES_StateRecord *nes_state_record(NES_RecordId record_id)
{
	return serialize_record_from_id(&nes_records, (u16)record_id);
}

const NES_StateField *nes_state_field_from_id(NES_StateFieldID id)
{
	if (id <= NES_STATE_FIELD_ID_NONE || id >= NES_STATE_FIELD_ID_COUNT)
	{
		return 0;
	}

	for (u32 type = 0; type < ArrayCount(nes_state_records); ++type)
	{
		const NES_StateRecord *record = &nes_state_records[type];
		for (u32 field_index = 0; field_index < record->field_count; ++field_index)
		{
			const NES_StateField *field = &record->fields[field_index];
			if (field->id == id) return field;
		}
	}
	return 0;
}

u32 nes_state_visible_field_count(const NES_StateRecord *record)
{
	Assert(record);
	u32 count = 0;
	for (u32 index = 0; index < record->field_count; ++index)
	{
		count += !!(record->fields[index].flags & NES_STATE_FIELD_DEBUG_VISIBLE);
	}
	return count;
}

const NES_StateField *nes_state_visible_field(
	const NES_StateRecord *record, u32 visible_index)
{
	Assert(record);
	for (u32 index = 0; index < record->field_count; ++index)
	{
		const NES_StateField *field = &record->fields[index];
		if (!(field->flags & NES_STATE_FIELD_DEBUG_VISIBLE)) continue;
		if (visible_index == 0) return field;
		--visible_index;
	}
	return 0;
}
